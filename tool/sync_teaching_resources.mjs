// Export Aule Server's original ES/EN lessons as typed, offline Flutter data.
// Run from the app root: node tool/sync_teaching_resources.mjs ../aule-sw
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

if (!process.argv[2]) throw new Error("Pass the path to an aule-sw checkout");
const source = resolve(process.argv[2], "apps/playground/public/teaching-resources.js");
const { listTeachingResources, teachingResource } = await import(pathToFileURL(source));
const quote = (text) => JSON.stringify(text).replaceAll("$", "\\$");
const fields = ["title", "goal", "prompt", "workedExample", "plan", "rubric", "exitTicket", "answerKey"];
const lines = [
  "// SPDX-License-Identifier: Apache-2.0",
  "// Generated by tool/sync_teaching_resources.mjs from Aule Server. Do not edit.",
  "part of 'lesson.dart';", "", "const _lessons = <String, List<Lesson>>{",
];
for (const language of ["es", "en"]) {
  lines.push(`  "${language}": [`);
  for (const { id } of listTeachingResources(language)) {
    const pack = teachingResource(id, language);
    lines.push("    Lesson(", `      id: ${quote(id)},`);
    for (const field of fields) {
      const value = pack[field];
      if (Array.isArray(value)) {
        lines.push(`      ${field}: [`, ...value.map((line) => `        ${quote(line)},`), "      ],");
      } else {
        lines.push(`      ${field}: ${quote(value)},`);
      }
    }
    lines.push("    ),");
  }
  lines.push("  ],");
}
lines.push("};", "");
await writeFile(new URL("../lib/features/resources/lessons.g.dart", import.meta.url), lines.join("\n"));
